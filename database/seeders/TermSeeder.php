        foreach ($this->terms() as $order => $data) {
            $term = Term::updateOrCreate(
                ['slug' => $data['slug']],
                [
                    'name' => $data['name'],
                    'summary' => $data['summary'],
                    'explanation' => $data['explanation'],
                    'analogy' => $data['analogy'],
                    'points' => $data['points'],
                    'sort_order' => $order + 1,
                ],
            );

            $question = $term->quizQuestion()->updateOrCreate([], ['question' => $data['quiz']['question']]);

            $question->choices()->delete();

            foreach ($data['quiz']['choices'] as $index => [$body, $feedback]) {
                $question->choices()->create([
                    'body' => $body,
                    'feedback' => $feedback,
                    'sort_order' => $index + 1,
                ]);
            }
        }
    }

